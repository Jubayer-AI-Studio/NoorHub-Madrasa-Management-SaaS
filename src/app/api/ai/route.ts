export async function POST(req: Request) {
  try {
    const body = await req.json();
    const { message, history = [], apiKey } = body;

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 });
    }

    const trimmedMsg = message.trim();

    // Check for Gemini API key
    const activeApiKey = apiKey?.trim() || process.env.GEMINI_API_KEY || process.env.GOOGLE_AI_API_KEY || '';

    if (activeApiKey) {
      try {
        const contents: any[] = [
          {
            role: 'user',
            parts: [{ text: `${NOORHUB_SYSTEM_PROMPT}\n\nএখন থেকে এই নির্দেশনা অনুযায়ী পরবর্তী বার্তাগুলোর উত্তর দাও।` }],
          },
          {
            role: 'model',
            parts: [{ text: 'আলহামদুলিল্লাহ, আমি নূর এআই প্রস্তুত। নূরহাবের সকল ফিচার, মাদরাসা কারিকুলাম ও দ্বীনি শিক্ষার যেকোনো বিষয়ে বিস্তারিত ও সুনির্দিষ্ট উত্তর দেব।' }],
          },
        ];

        const recentHistory = Array.isArray(history) ? history.slice(-6) : [];
        for (const item of recentHistory) {
          if (item.sender === 'user') {
            contents.push({ role: 'user', parts: [{ text: item.text }] });
          } else if (item.sender === 'ai') {
            contents.push({ role: 'model', parts: [{ text: item.text }] });
          }
        }

        contents.push({ role: 'user', parts: [{ text: trimmedMsg }] });

        const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${activeApiKey}`;
        const geminiRes = await fetch(geminiUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents,
            generationConfig: {
              temperature: 0.7,
              maxOutputTokens: 1024,
            },
          }),
        });

        if (geminiRes.ok) {
          const geminiData = await geminiRes.json();
          const generatedText = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;
          if (generatedText) {
            return NextResponse.json({
              text: generatedText,
              provider: 'gemini',
            });
          }
        }
      } catch {
        // Fall back gracefully to the local engine
      }
    }

    // Local Comprehensive Knowledge Engine (Zero Generic Fallback)
    const localResponse = getIntelligentResponse(trimmedMsg);
    return NextResponse.json({
      text: localResponse.text,
      actionLink: localResponse.actionLink,
      provider: 'local-engine',
    });
  } catch {
    return NextResponse.json(
      {
        text: 'আস-সালামু আলাইকুম। বার্তাটি প্রক্রিয়াকরণে কিছুটা বিঘ্ন ঘটেছে। দয়া করে আবার বলুন, আমি উত্তর দিতে প্রস্তুত।',
        provider: 'fallback',
      },
      { status: 500 }
    );
  }
}

